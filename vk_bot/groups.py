"""
Справочник курсов, направлений и групп.

ВНИМАНИЕ: это НЕ копия данных из вашего проекта — у вас в Telegram-боте
структура GROUPS может отличаться. Перед запуском сверьте этот файл
с реальным bot.py (или schedule.json) вашего проекта D:\\Downloads\\VFStudentBot
и при необходимости поправьте. Мы не добавляем группы вроде ИСП-261,
которых в расписании нет.

Направления РУПО и ЗСП/ЭСП/ЮСП — разные пункты меню, как в TG-боте.
"""

# (курс, направление) -> список групп
GROUPS: dict[tuple[int, str], list[str]] = {
    (1, "РУПО"): ["РУПО-261", "РУПО-262", "РУПО-263", "РУПО-264", "РУПО-265"],
    (2, "ИСП"):  ["ИСП-251", "ИСП-252", "ИСП-253", "ИСП-254"],
    (3, "ИСП"):  ["ИСП-241", "ИСП-242", "ИСП-243"],
    (4, "ИСП"):  ["ИСП-231", "ИСП-232", "ИСП-233"],
    (1, "ЗСП"):  ["ЗСП-261", "ЗСП-262"],
    (2, "ЗСП"):  ["ЗСП-251", "ЗСП-252"],
    (3, "ЗСП"):  ["ЗСП-241"],
    (4, "ЗСП"):  ["ЗСП-231"],
    (1, "ЭСП"):  ["ЭСП-261"],
    (2, "ЭСП"):  ["ЭСП-251"],
    (3, "ЭСП"):  ["ЭСП-241"],
    (1, "ЮСП"):  ["ЮСП-261", "ЮСП-262"],
    (2, "ЮСП"):  ["ЮСП-251", "ЮСП-252", "ЮСП-263"],
    (3, "ЮСП"):  ["ЮСП-241", "ЮСП-242", "ЮСП-253"],
}


def get_courses() -> list[int]:
    """Все курсы, которые встречаются в структуре (по возрастанию)."""
    return sorted({course for (course, _faculty) in GROUPS})


def get_faculties(course: int) -> list[str]:
    """Направления (факультеты) для выбранного курса."""
    return sorted({fac for (c, fac) in GROUPS if c == course})


def get_groups(course: int, faculty: str) -> list[str]:
    """Группы для выбранной пары (курс, направление)."""
    return GROUPS.get((course, faculty), [])


def find_group(group_name: str) -> tuple[int, str] | None:
    """Находит (курс, направление) по названию группы. None, если группы нет."""
    for (course, faculty), groups in GROUPS.items():
        if group_name in groups:
            return course, faculty
    return None
